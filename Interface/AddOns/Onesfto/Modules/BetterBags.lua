local consumableCache = {}
local scanner = nil

local function GetDynamicCategory(itemLink, itemID)
    if consumableCache[itemID] then
        if consumableCache[itemID] == "NONE" then return nil end
        return consumableCache[itemID]
    end
    
    if not scanner then
        scanner = CreateFrame("GameTooltip", "OnesftoBetterBagsTooltipScanner", nil, "GameTooltipTemplate")
    end
    
    scanner:SetOwner(WorldFrame, "ANCHOR_NONE")
    scanner:ClearLines()
    scanner:SetHyperlink(itemLink)
    
    if scanner:NumLines() <= 1 then
        return nil
    end
    
    local text = ""
    for i = 1, scanner:NumLines() do
        local line = _G["OnesftoBetterBagsTooltipScannerTextLeft" .. i]
        if line and line:GetText() then
            text = text .. " " .. line:GetText()
        end
    end
    
    local cat = nil
    if string.match(text, "坐骑") or string.match(text, "教你学会召唤") or string.match(text, "右键点击以召唤") or string.match(text, "召唤或解散") or string.match(text, "骑术") then
        cat = "坐骑宠物玩具"
    end
    
    consumableCache[itemID] = cat or "NONE"
    return cat
end

