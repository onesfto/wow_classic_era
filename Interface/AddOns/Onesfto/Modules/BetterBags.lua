        if Custom_CSV_Items[itemID] then 
            return Custom_CSV_Items[itemID]
        end

        local dynamicCat = GetDynamicCategory(data.itemInfo.itemLink, itemID)
        if dynamicCat then
            return dynamicCat
        end

        if data.itemInfo.itemName then
