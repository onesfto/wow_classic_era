-- GW2_UI 汉化增量 (zhCN) —— GW2 UI Plus 先行加载组件
--
-- 为什么这个文件不在 GW2_UI_PLUS 里？
--
-- 经典旧世下 GW2_UI 在它自己的 ADDON_LOADED 里就跑完了 evPlayerLogin，
-- 把整个设置窗口连同几百条 L["..."] 文本一次性建好了。而 GW2_UI_PLUS 声明了
-- Dependencies: GW2_UI，必然在这之后才加载——那时候再往 L 表里补词条已经晚了，
-- 界面上的文字早就定死成英文了。这正是之前「翻译没生效」的原因。
--
-- 所以把词条挪到这个 "!" 开头的先行加载插件里，赶在 GW2_UI 之前用 AceLocale 注册。
-- AceLocale 的 apps 表是按插件名共享的，GW2_UI 随后注册自己的 enUS/zhCN 时会并进同一张表；
-- 而且默认语言包(enUS)用的 writedefaultproxy 明确拒绝覆盖已有值，所以我们先写的中文能保住。
--
-- 代价是多一个插件文件夹，但 GW2_UI 本体仍然一个字都没动，升级照样直接覆盖解压。
--
-- 词条来源：Onesfto/Modules/GW2_UI/汉化/gw2_zhCN.lua 相对上游 zhCN.lua 的增量。
-- 不走语言包的硬编码文本在 GW2_UI_PLUS/locale/Hardcoded.lua 里处理。

